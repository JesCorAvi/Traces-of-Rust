function drawScrew0(px, key) {
  px(3, 3, 10, 10, '#050605');
  px(4, 4, 8, 8, '#4a2518');
  px(5, 4, 6, 2, '#877a5c');
  if (key === 'screw_0') px(4, 7, 8, 2, '#050605');
  else if (key === 'screw_1') px(7, 4, 2, 8, '#050605');
  else if (key === 'screw_2') {
    for (let i = 0; i < 6; i++) px(5 + i, 5 + i, 2, 2, '#050605');
  } else {
    for (let i = 0; i < 6; i++) px(10 - i, 5 + i, 2, 2, '#050605');
  }
}

